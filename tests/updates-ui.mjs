import assert from 'node:assert/strict';
import { cp, mkdtemp, readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { chromium } from 'playwright-core';
import { closeTestContext } from './ui-helpers.mjs';
const root = resolve(import.meta.dirname, '..'), prefix = 'MeowlChess-updates-test-';
const profile = await mkdtemp(join(tmpdir(), prefix)), bundle = await mkdtemp(join(tmpdir(), 'MeowlChess-updates-bundle-'));
const extension = join(bundle, 'extension'); let context;
const errors = [], requests = [];
try {
  await cp(join(root, 'extension'), extension, { recursive: true });
  const manifest = JSON.parse(await readFile(join(extension, 'manifest.json'), 'utf8'));
  const [major, minor] = manifest.version.split('.').map(Number);
  const nextVersion = `${major}.${minor + 1}.0`;
  manifest.host_permissions.push('https://api.github.com/*');
  manifest.optional_host_permissions = manifest.optional_host_permissions.filter(origin => !origin.includes('api.github.com'));
  await writeFile(join(extension, 'manifest.json'), JSON.stringify(manifest));
  context = await chromium.launchPersistentContext(profile, { executablePath: process.env.CHROMIUM_PATH || 'C:\\Program Files\\BraveSoftware\\Brave-Browser\\Application\\brave.exe', headless: true, viewport: { width: 1200, height: 1000 }, reducedMotion: 'reduce', ignoreDefaultArgs: ['--disable-extensions'], args: [`--disable-extensions-except=${extension}`, `--load-extension=${extension}`] });
  context.setDefaultTimeout(15000);
  console.log('Update flow: browser started');
  context.on('request', request => { if (/^https?:/.test(request.url())) requests.push(request.url()); });
  const worker = context.serviceWorkers().find(item => item.url().startsWith('chrome-extension://')) || await context.waitForEvent('serviceworker', { timeout: 15000 });
  const base = `chrome-extension://${new URL(worker.url()).hostname}`;
  await worker.evaluate(async nextVersion => {
    await chrome.storage.local.set({ usernames: { chesscom: 'BackupCat', lichess: 'BackupOwl' }, reviewSettings: { boardSize: 640, engine: 'lozza' }, tutorialNeverShowAgain: true, supportNeverShowAgain: true });
    globalThis.updateRequests = 0;
    const nativeFetch = globalThis.fetch;
    globalThis.fetch = (url, options) => {
      if (url === 'https://api.github.com/repos/ThuyTran735/MeowlChess/releases/latest') {
        globalThis.updateRequests++;
        return Promise.resolve(new Response(JSON.stringify({ draft: false, prerelease: false, tag_name: `v${nextVersion}`, html_url: `https://github.com/ThuyTran735/MeowlChess/releases/tag/v${nextVersion}`, body: 'A calmer update experience.\n<script>bad()</script>', assets: [{ name: 'MeowlChess.zip', state: 'uploaded', size: 234, browser_download_url: `https://github.com/ThuyTran735/MeowlChess/releases/download/v${nextVersion}/MeowlChess.zip` }] })));
      }
      return nativeFetch(url, options);
    };
  }, nextVersion);
  const page = await context.newPage(); page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${base}/updates.html`);
  console.log('Update flow: page loaded');
  await page.waitForFunction(() => document.querySelector('#current-version').textContent.startsWith('v'));
  assert.equal(await worker.evaluate(() => globalThis.updateRequests), 0, 'Opening page is offline by default');
  const recordId = await page.evaluate(async () => {
    const { createReviewLibrary } = await import('./lib/library.js');
    const { analyzeGame, ANALYSIS_VERSION } = await import('./lib/review.js');
    const { importPgn } = await import('./lib/pgn.js');
    const pgn = '[Event "Backup example"]\n[White "BackupCat"]\n[Black "OtherCat"]\n[Result "1-0"]\n\n1. e4 e5 2. Nf3 1-0';
    const result = await analyzeGame(pgn, { smartAnalysis: false, engineFactory: () => ({ async init() {}, dispose() {}, async evaluate() { return { cp: 0, mate: null, bestMove: null, pv: [], candidates: [], depth: 8 }; } }) });
    const library = createReviewLibrary({ analysisVersion: ANALYSIS_VERSION });
    const record = await library.saveReview(importPgn(pgn), result, { engineId: 'stockfish', engineName: 'Stockfish 18', moveTimeMs: 150, multiPV: 1, smartAnalysis: false, analysisVersion: ANALYSIS_VERSION });
    await library.toggleBookmark(record.id, 1, { note: 'Study this move' }); await library.close(); return record.id;
  });
  const downloadPromise = page.waitForEvent('download'); await page.locator('#export-backup').click(); const download = await downloadPromise;
  assert.match(download.suggestedFilename(), /^MeowlChess-backup-/);
  const backupText = await readFile(await download.path(), 'utf8');
  console.log('Update flow: backup exported');
  const backup = JSON.parse(backupText); assert.equal(backup.library.reviews.length, 1); assert.equal(backup.library.reviews[0].bookmarks[0].note, 'Study this move'); assert.equal(backup.settings.usernames.chesscom, 'BackupCat');
  await page.evaluate(async id => { const { createReviewLibrary } = await import('./lib/library.js'); const library = createReviewLibrary(); await library.deleteReview(id); await library.close(); await chrome.storage.local.set({ usernames: { chesscom: 'ChangedCat' }, reviewSettings: { boardSize: 880 } }); }, recordId);
  const file = { name: 'MeowlChess-backup.json', mimeType: 'application/json', buffer: Buffer.from(backupText) };
  await page.locator('#backup-file').setInputFiles(file);
  await page.locator('#restore-dialog').waitFor({ state: 'visible' }); assert.match(await page.locator('#restore-summary').innerText(), /1 saved reviews.*1 bookmarks/);
  await page.locator('#confirm-restore').click(); await page.locator('#restore-dialog').waitFor({ state: 'hidden' });
  console.log('Update flow: backup restored');
  assert.match(await page.locator('#backup-status').innerText(), /Restored 1 reviews/);
  assert.equal(await page.evaluate(async () => (await chrome.storage.local.get('usernames')).usernames.chesscom), 'BackupCat');
  assert.equal(await page.evaluate(async () => (await chrome.storage.local.get('reviewSettings')).reviewSettings.boardSize), 640);
  console.log('Update flow: preferences verified');
  await page.locator('#backup-file').setInputFiles(file); await page.locator('#restore-dialog').waitFor({ state: 'visible' }); await page.locator('#restore-settings').uncheck(); await page.locator('#confirm-restore').click(); await page.locator('#restore-dialog').waitFor({ state: 'hidden' });
  assert.match(await page.locator('#backup-status').innerText(), /Restored 0 reviews; kept 1 existing/);
  console.log('Update flow: duplicate merge verified');
  await page.locator('#backup-file').setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from('{"format":"wrong"}') });
  await page.waitForFunction(() => document.querySelector('#backup-status').textContent.includes('not a supported'));
  assert.equal(await page.locator('#restore-dialog').evaluate(el => el.open), false);
  console.log('Update flow: invalid backup rejected');
  await page.locator('#check-update').click(); await page.waitForFunction(version => document.querySelector('#update-heading').textContent.includes(version), nextVersion).catch(async error => { console.log(await page.locator('#update-status').innerText()); console.log(await worker.evaluate(async () => ({ requests: globalThis.updateRequests, cache: await chrome.storage.local.get('updateCheckState') }))); throw error; });
  console.log('Update flow: release checked');
  assert.equal(await worker.evaluate(() => globalThis.updateRequests), 1);
  assert.equal(await page.locator('#download-update').getAttribute('href'), `https://github.com/ThuyTran735/MeowlChess/releases/download/v${nextVersion}/MeowlChess.zip`);
  assert.match(await page.locator('#release-notes').textContent(), /<script>/); assert.equal(await page.locator('#release-notes script').count(), 0);
  await page.locator('#automatic-updates').check(); await page.waitForFunction(async () => (await chrome.storage.local.get('updatePreferences')).updatePreferences.automatic);
  const review = await context.newPage(); review.on('pageerror', error => errors.push(error.message)); await review.goto(`${base}/review.html?siteSettings=1`);
  assert.equal(await review.locator('#highlight-analysis').isChecked(), true);
  await review.locator('#highlight-analysis').uncheck();
  await review.waitForFunction(async () => (await chrome.storage.local.get('reviewSettings')).reviewSettings.highlights === false);
  await review.reload();
  assert.equal(await review.locator('#highlight-analysis').isChecked(), false);
  await review.locator('#close-settings').click();
  await review.locator('.update-notice').waitFor({ state: 'visible' }); await review.locator('.update-notice button').click(); await review.reload();
  await review.waitForFunction(async version => (await chrome.storage.local.get('updateDismissedVersion')).updateDismissedVersion === version, nextVersion);
  assert.equal(await review.locator('.update-notice').isVisible(), false);
  await page.evaluate(async () => chrome.storage.local.set({ backupRestoredAt: Date.now() }));
  await review.locator('#MeowlChess-refresh-notice').waitFor({ state: 'visible' }); assert.match(await review.locator('#MeowlChess-refresh-notice').innerText(), /Backup restored/);
  await review.close();
  const out = join(root, 'test-results'); await mkdir(out, { recursive: true });
  await page.screenshot({ path: join(out, 'MeowlChess-updates-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: join(out, 'MeowlChess-updates-mobile.png'), fullPage: true });
  assert.deepEqual(errors, []); assert.equal(requests.filter(url => url.includes('api.github.com')).length, 0);
  console.log('Update/backup browser flow complete.');
} catch (error) { console.error(error); throw error; } finally {
  await closeTestContext(context, profile, prefix);
  for (const path of [profile, bundle]) if (path.startsWith(tmpdir()) && /MeowlChess-updates-(test|bundle)-/.test(path)) await rm(path, { recursive: true, force: true, maxRetries: 5, retryDelay: 200 });
}
