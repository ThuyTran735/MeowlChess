import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { Chess } from '../extension/vendor/chess.js';

const root = resolve(import.meta.dirname, '..');
const source = resolve(root, 'third-party-source/chess-openings');
const provenance = JSON.parse(await readFile(resolve(source, 'provenance.json'), 'utf8'));
const lines = [];
for (const file of ['a.tsv', 'b.tsv', 'c.tsv', 'd.tsv', 'e.tsv']) {
  const rows = (await readFile(resolve(source, file), 'utf8')).trim().split(/\r?\n/);
  if (rows.shift() !== 'eco\tname\tpgn') throw new Error(`Unexpected opening data header: ${file}`);
  for (const row of rows) {
    const [eco, name, pgn, extra] = row.split('\t');
    if (!/^[A-E]\d\d$/.test(eco) || !name || !pgn || extra !== undefined) throw new Error(`Invalid opening: ${row}`);
    const chess = new Chess();
    chess.loadPgn(pgn);
    const moves = chess.history({ verbose: true }).map(move => move.from + move.to + (move.promotion || ''));
    if (!moves.length) throw new Error(`Empty opening: ${name}`);
    lines.push([eco, name, moves.join(' ')]);
  }
}
await mkdir(resolve(root, 'extension/data'), { recursive: true });
const output = `// Generated by scripts/build-openings.mjs from the pinned CC0 Lichess dataset.\nexport const OPENING_DATA_VERSION = ${JSON.stringify(provenance.revision)};\nexport const OPENING_LINES = [\n${lines.map(line => JSON.stringify(line)).join(',\n')}\n];\n`;
await writeFile(resolve(root, 'extension/data/openings.js'), output);
console.log(`Built ${lines.length} local opening lines (${Buffer.byteLength(output)} bytes).`);
